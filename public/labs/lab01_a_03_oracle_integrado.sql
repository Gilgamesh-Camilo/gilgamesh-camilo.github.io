SET SERVEROUTPUT ON;

-- 1. DDL NORMALIZADO 3FN E INDEXACIÓN DE LLAVES FORÁNEAS
CREATE TABLE his_pacientes (
    id_paciente     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento       VARCHAR2(20) NOT NULL UNIQUE,
    nombre_completo VARCHAR2(120) NOT NULL,
    alergia_activa  VARCHAR2(80),
    estado          VARCHAR2(15) DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE his_medicamentos (
    id_medicamento  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_atc      VARCHAR2(20) NOT NULL UNIQUE,
    nombre          VARCHAR2(100) NOT NULL,
    principio_activo VARCHAR2(80) NOT NULL,
    stock_actual    NUMBER(10) DEFAULT 0 CHECK (stock_actual >= 0),
    fecha_vencimiento DATE NOT NULL
);

CREATE TABLE his_formulas (
    id_formula      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente     NUMBER NOT NULL REFERENCES his_pacientes(id_paciente),
    id_medicamento  NUMBER NOT NULL REFERENCES his_medicamentos(id_medicamento),
    cantidad        NUMBER(5) NOT NULL CHECK (cantidad > 0),
    estado          VARCHAR2(15) DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA', 'DISPENSADA', 'ANULADA')),
    fecha_formula   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE his_log_errores (
    id_log          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedimiento   VARCHAR2(60),
    codigo_ora      NUMBER,
    mensaje_error   VARCHAR2(500),
    usuario_bd      VARCHAR2(50),
    fecha_registro  TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Índices explícitos sobre Foreign Keys (previene bloqueos Table Lock TM)
CREATE INDEX ix_formulas_paciente_fk ON his_formulas (id_paciente);
CREATE INDEX ix_formulas_medicamento_fk ON his_formulas (id_medicamento);
-- Índice compuesto aplicando regla ESR (Igualdad primero, Rango después)
CREATE INDEX ix_formulas_estado_fecha ON his_formulas (estado, fecha_formula);
-- Índice basado en función (FBI) para búsquedas insensibles a mayúsculas
CREATE INDEX ix_pacientes_upper_nom ON his_pacientes (UPPER(nombre_completo));

-- 2. COMPOUND TRIGGER PARA PREVENCIÓN DE MUTATING TABLE (ORA-04091)
CREATE OR REPLACE TRIGGER tgr_cmp_validar_polifarmacia
FOR INSERT OR UPDATE ON his_formulas
COMPOUND TRIGGER
    TYPE t_pacientes_tab IS TABLE OF his_formulas.id_paciente%TYPE INDEX BY PLS_INTEGER;
    v_pacientes t_pacientes_tab;

    AFTER EACH ROW IS
    BEGIN
        v_pacientes(v_pacientes.COUNT + 1) := :NEW.id_paciente;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        v_total_activos NUMBER;
    BEGIN
        FOR i IN 1 .. v_pacientes.COUNT LOOP
            SELECT COUNT(*) INTO v_total_activos
            FROM his_formulas
            WHERE id_paciente = v_pacientes(i) AND estado = 'ACTIVA';

            IF v_total_activos > 3 THEN
                RAISE_APPLICATION_ERROR(-20022, 'Alerta clínica: el paciente supera el límite de 3 fórmulas activas.');
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END tgr_cmp_validar_polifarmacia;
