-- 3. PAQUETE MODULAR PL/SQL CON TRANSACCIÓN AUTÓNOMA Y BLOQUEO PESIMISTA
CREATE OR REPLACE PACKAGE pck_dispensacion_medica AS
    PROCEDURE sp_dispensar_medicamento(
        p_id_paciente    IN NUMBER,
        p_id_medicamento IN NUMBER,
        p_cantidad       IN NUMBER
    );
END pck_dispensacion_medica;
/

CREATE OR REPLACE PACKAGE BODY pck_dispensacion_medica AS

    PROCEDURE sp_registrar_error_autonomo(
        p_procedimiento IN VARCHAR2,
        p_codigo_ora    IN NUMBER,
        p_mensaje       IN VARCHAR2
    ) IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        INSERT INTO his_log_errores (procedimiento, codigo_ora, mensaje_error, usuario_bd)
        VALUES (p_procedimiento, p_codigo_ora, SUBSTR(p_mensaje, 1, 500), USER);
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
    END sp_registrar_error_autonomo;

    PROCEDURE sp_dispensar_medicamento(
        p_id_paciente    IN NUMBER,
        p_id_medicamento IN NUMBER,
        p_cantidad       IN NUMBER
    ) IS
        vv_alergia       his_pacientes.alergia_activa%TYPE;
        vv_principio     his_medicamentos.principio_activo%TYPE;
        vn_stock         his_medicamentos.stock_actual%TYPE;
        vd_vencimiento   his_medicamentos.fecha_vencimiento%TYPE;
        e_regla_clinica  EXCEPTION;
        PRAGMA EXCEPTION_INIT(e_regla_clinica, -20015);
    BEGIN
        SELECT alergia_activa INTO vv_alergia
        FROM his_pacientes
        WHERE id_paciente = p_id_paciente AND estado = 'ACTIVO';

        -- Bloqueo pesimista a nivel de fila (TX) para evitar Lost Update en inventario
        SELECT principio_activo, stock_actual, fecha_vencimiento
        INTO vv_principio, vn_stock, vd_vencimiento
        FROM his_medicamentos
        WHERE id_medicamento = p_id_medicamento
        FOR UPDATE;

        IF vv_alergia IS NOT NULL AND UPPER(vv_alergia) = UPPER(vv_principio) THEN
            RAISE_APPLICATION_ERROR(-20015, 'Contraindicación: paciente alérgico a ' || vv_principio);
        END IF;

        IF vd_vencimiento < TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20016, 'Lote vencido: no se permite dispensar el medicamento.');
        END IF;

        IF vn_stock < p_cantidad THEN
            RAISE_APPLICATION_ERROR(-20017, 'Stock insuficiente en farmacia.');
        END IF;

        UPDATE his_medicamentos
        SET stock_actual = stock_actual - p_cantidad
        WHERE id_medicamento = p_id_medicamento;

        INSERT INTO his_formulas (id_paciente, id_medicamento, cantidad, estado)
        VALUES (p_id_paciente, p_id_medicamento, p_cantidad, 'ACTIVA');

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            sp_registrar_error_autonomo('PCK_DISPENSACION_MEDICA.SP_DISPENSAR_MEDICAMENTO', SQLCODE, SQLERRM);
            RAISE;
    END sp_dispensar_medicamento;

END pck_dispensacion_medica;
